TESTS = ["따뜻하고 가족적인 학부모 발표", "엄숙한 이사회 결산 보고", "젊은이 캠프 홍보", "연구 발표 · 데이터 중심", "고요한 추모식", "다크 테마 기술 해설 영상"]
def pick(text, styles):
    rows = []
    for s in styles:
        strong, use, weak, anti = LEX[s["id"]]; score, why = 0, []
        for words, pt in ((strong, 3), (use, 2), (weak, 1), (anti, -3)):
            for w in words:
                if w.lower() in text.lower(): score += pt; why.append(f"{w}({pt:+d})")
        rows.append((score, -s["no"], s, why))
    rows.sort(key=lambda r: (r[0], r[1]), reverse=True)  # 동점이면 번호가 앞선 쪽
    return rows
def main():
    styles = json.loads((HERE / "styles.json").read_text(encoding="utf-8"))
    assert set(LEX) == {s["id"] for s in styles}, "LEX 와 styles.json 의 id 가 어긋난다"
    if len(sys.argv) > 1 and sys.argv[1] == "--test":
        out = ["# 선택기 시험 — 묘사 6문장 (pick.py --test 출력)", "",
               "| 묘사 | 1순위 | 점수 | 근거(일치한 낱말) | 2순위 | 점수 | 근거(일치한 낱말) |", "|---|---|---|---|---|---|---|"]
        for t in TESTS:
            r = pick(t, styles); a, b = r[0], r[1]
            out.append(f"| {t} | {a[2]['no']}. {a[2]['name']} | {a[0]} | {' '.join(a[3]) or '없음'} | {b[2]['no']}. {b[2]['name']} | {b[0]} | {' '.join(b[3]) or '없음'} |")
        print("\n".join(out)); return
    text = " ".join(sys.argv[1:]).strip()
    if not text: print(__doc__); sys.exit(2)
    r = pick(text, styles)
    if r[0][0] <= 0: print(f"일치어 없음 — 「{text}」 에서 아는 낱말을 찾지 못했다. references/CATALOG.md 「한눈에 보기」 의 묘사어 표에서 직접 고른다."); sys.exit(1)
    for rank, (score, _, s, why) in enumerate(r[:2], 1):
        print(f"{rank}순위  {s['no']}. {s['name']}  [{s['id']}]  점수 {score}\n       근거: {' '.join(why) or '없음'}\n       코드: {s['file']} · 미리보기: bash run.sh samples {s['id']}")
    if r[1][0] <= 0: print("※ 2순위는 일치한 낱말이 없어 번호 순으로 나온 것이다 — 참고만.")
if __name__ == "__main__": main()
