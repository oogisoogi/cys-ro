// 부서 생성 확인 문안 — 「무엇이 바뀌는지」 3줄 (박사님 판정 2026-09-20 ⓒ · TICKET=v110-sidebar)
//
// ★이 파일이 존재하는 이유는 B22(2026-09-20 05:02)다. ＋부서 한 번 클릭이 확인 창도 토스트도 없이
//   곧장 실행돼 본부 지침 파일(MASTER_DIRECTIVE.md)이 CEO 템플릿으로 교체됐다(854 보고서 §3).
//   그 사고에서 확인 창보다 더 중요했던 것은 **무엇이 바뀌는지 아무 데도 안 적혀 있었다**는 점이다 —
//   854 §5 가 적은 대로 확인 창은 「실수로 눌렀다」만 막고 「그게 무슨 뜻인지 몰랐다」는 못 막는다.
//   그래서 문안을 화면 코드가 아니라 여기에 두고, 세 축이 실제로 적혀 있는지를 시험이 센다.
//
// ★세 축은 cys-dept 가 부서 하나마다 실제로 하는 일에서 왔다(854 §0-1 표 · 실측):
//   ① 독립 cysd 데몬 1개 추가(cys-dept:1263) ② 상비편성 3좌석 ensure(cys-dept:1300)
//   ③ 본부 팩의 MASTER_DIRECTIVE.md → CEO_TEMPLATE.md 교체(cys-dept:1270 → :918)
//   ③에는 **되돌아가는 조건**까지 함께 적는다 — 부서가 0개가 되면 자동 강등된다(cys-dept:1508 → :1002).
//   조건 없이 「바뀝니다」만 적으면 비가역으로 읽혀 과잉 공포를 준다(정직의 방향이 반대로 틀린다).
//
// ★말투는 사이드바 안내 한 줄과 같은 층이다(왕초보). 다만 ③은 파일 이름을 적는다 — 이 줄은
//   「모르고 눌렀다」를 막는 것이 목적이라, 나중에 경보를 본 사람이 같은 이름을 찾을 수 있어야 한다.

export interface ConfirmSpec {
  title: string;
  body: string;
  /** 진행 단추 글자 — 기본값("확인")을 쓰지 않는다. 무엇을 승인하는지가 단추에 적혀야 한다. */
  yes: string;
  /** 취소 단추 글자 — confirmModal 이 이쪽에 기본 포커스를 준다(무심코 친 Enter = 취소). */
  no: string;
}

/** 부서 생성(＋부서·팔레트 모두 같은 문) 확인 문안. 본문은 정확히 3줄이다. */
export function deptCreateConfirm(): ConfirmSpec {
  return {
    title: "새 부서를 만들까요?",
    body: [
      "· 이 컴퓨터에 부서 전용 프로그램(데몬)이 하나 더 켜집니다",
      "· 그 부서에 일할 자리 3개(마스터·CSO·워커)가 자동으로 만들어집니다",
      "· 본부 마스터 지침 파일(MASTER_DIRECTIVE.md)이 CEO 규약으로 교체됩니다 — 부서를 모두 지우면 되돌아갑니다",
    ].join("\n"),
    yes: "부서 만들기",
    no: "취소",
  };
}
