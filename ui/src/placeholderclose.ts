//
// ── 무엇을 고치는가 ────────────────────────────────────────────────────────────
// 앱이 콜드로 뜨면 복원 루프가 「입양할 노드가 아직 없는 탭」을 빈 화면으로 두지 않으려고
// 역할 없는 맨 셸을 하나 만든다(자리표). 그 뒤 편성이 자기 자리들을 따로 만들기 때문에
// 화면에는 자리표 1 + 편성 3 = 4자리가 남는다. 재시작 복원 경로는 입양할 좌석이 이미 있어
// 자리표가 안 생기고 3자리다 — 같은 제품이 경로에 따라 다르게 보이는 것이 B17 이다.
//
// ── 왜 「닫기」이고 「승계」가 아닌가(master 판정) ─────────────────────────────
// 승계안(맨 셸을 편성 첫 자리로 재사용)은 **박사님이 직접 연 터미널 페인도 역할 없는 맨 셸**이라
// 같은 그물에 걸린다 — 실패 방향이 남의 작업창 탈취다. 닫기안은 **UI 가 자기가 만든 번호만**
// 기억하므로 남의 페인은 원리적으로 대상 밖이다(번호가 다르다).
//
// ── 이 모듈의 보장·비보장 ─────────────────────────────────────────────────────
// · 보장: 여기서 true 가 나오는 자리는 ⓐ UI 가 만든 자리표이고 ⓑ 사람이 손대지 않았고
//   ⓒ 그 탭에 진짜 역할 좌석이 이미 붙었다. 셋 중 하나라도 모르면 **false**(fail-closed).
// · 비보장: 「손댔다」의 판정은 두 축(입력 이력 · 화면 줄 수)으로만 본다. 사람이 자리표를
//   보기만 하고 아무것도 안 했는데 셸이 스스로 여러 줄을 찍는 환경(motd 등)에서는 닫지 않는다
//   — 그쪽으로 틀리는 것이 옳다(안 닫으면 잡음 1개, 잘못 닫으면 사람의 작업이 사라진다).

/**
 * 맨 셸이 자기 프롬프트 말고는 아무것도 안 찍었다고 볼 수 있는 줄 수의 상한.
 * 프롬프트 1줄 + 커서줄 + 여유 1 = 3. 이 값을 키우면 「사람이 명령을 한 번 돌린 자리」가
 * 무접촉으로 접히므로, 키우려면 실측 근거를 함께 적어라.
 */
export const PLACEHOLDER_MAX_LINES = 3;

export interface PlaceholderDecision {
  /** ⓐ UI 가 **자기가 만든** 자리표로 기억하는 번호인가. 아니면 남의 페인이다. */
  isOwnPlaceholder: boolean;
  /** ⓑ 이 자리에 키 입력을 한 번이라도 보냈는가(UI 의 단일 입력 경로가 표시한다). */
  touched: boolean;
  /** 자리표에 역할이 붙었으면 그것은 더 이상 자리표가 아니다(입양·승계된 좌석). */
  role: string | null;
  /** ⓑ 화면 줄 수(모르면 null — 모르면 닫지 않는다). */
  lineCount: number | null;
  /** ⓑ 그 탭에 진짜 역할 좌석이 붙었는가. 안 붙었으면 자리표가 유일한 화면이다. */
  formationArrived: boolean;
  /** 이미 죽은 자리는 이 경로가 아니라 죽은 pane 정리가 가져간다. */
  exited: boolean;
}

/**
 * 이 자리를 지금 닫아도 되는가. **모르면 닫지 않는다**(모든 미지는 false 로 접는다).
 *
 * 순서는 「가장 위험한 축을 먼저」다 — ⓐ 남의 페인 여부가 첫 관문이고, 그 뒤에 무접촉,
 * 마지막이 편성 도착이다. 순서를 바꾸면 판정은 같지만 읽는 사람이 무엇이 절대 조건인지 잃는다.
 */
export function shouldClosePlaceholder(d: PlaceholderDecision): boolean {
  if (!d.isOwnPlaceholder) return false; // ⓐ 남의 페인 절대 불가침
  if (d.touched) return false; // ⓒ 손댔으면 그대로 둔다(알림도 없다)
  if (d.role !== null) return false; // 역할이 붙었다 = 자리표가 아니다
  if (d.exited) return false; // 죽은 자리는 죽은 pane 정리 소관
  if (d.lineCount === null) return false; // 모르면 닫지 않는다
  if (d.lineCount > PLACEHOLDER_MAX_LINES) return false; // ⓑ 프롬프트 밖 출력이 있다
  return d.formationArrived; // ⓑ 편성이 도착한 뒤에만
}
